export function getStudentCopy(language: string) {
  if (language in copy) return copy[language as keyof typeof copy];
  return copy.English;
}

export function useStudentCopy() {
  const preferences = useStudentPreferences();
  return getStudentCopy(preferences.accessibilityMode === "Multilingual" ? preferences.language : "English");
}
